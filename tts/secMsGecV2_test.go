package tts

import "testing"

// 参考向量由 rany2/edge-tts 官方 drm.py 生成，用于验证 Go 移植的一致性。
func TestGenerateSecMSGECV2(t *testing.T) {
	cases := []struct {
		timestamp float64
		want      string
	}{
		{1700000000, "2CD23A2CA0B2595A-F3C846C370E05F9CC83ACC5F995C5F5D87A4D0F14CE8936A0F902E64099E38A2"},
		{1700000300, "0919602B5750900A-EC9DD394F23CB5635CF62A0E8E24136DCD32B26D10C543B10082E482D7516397"},
		{1712345678, "5EEFCDB6BB925924-EF25132E29C4B6608F2627793735A304B8F58EFFEA7FF29EED6CFF3AECDE34B6"},
		{1720000000, "576EF243D9E6C36D-B73D5ADB984074BAE7860791FCA9CE1D28D1F6678CE5644A7981ACCA7E3C0EF2"},
		{1793531336, "6796E2F070230102-8B64653F8E0093F87C30A0CF6EB9E6F16AB5EF685D266FACC74C90A5F39D0849"},
		{1800000000, "99E54519B490BE5C-E162DB0977FBDCB9B86DD8148BF1BCDC3C0303176CE39852A42B415935C20654"},
	}

	for _, c := range cases {
		got := generateSecMSGECV2(c.timestamp)
		if got != c.want {
			t.Errorf("generateSecMSGECV2(%v) = %s, want %s", c.timestamp, got, c.want)
		}
	}
}
